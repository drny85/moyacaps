export interface CapVariant {
  id: string;
  nameEn: string;
  nameEs: string;
  silhouette: ProductSilhouette;
  category?: ProductCategory;
  primaryHex: string;
  secondaryHex: string;
  image: string;
  images?: string[];
  /** 4:5 Catalog Shot for grids and cards (ADR 0016) */
  catalogShot?: string;
  /** The four turntable photos, present only when all four are uploaded (ADR 0021) */
  angles?: Record<CapAngleKey, string>;
  graphicImage?: string;
  printPosition?: "front" | "back";
  stock: number;
  priceUsd: number;
  isFeatured?: boolean;
  tagEn?: string;
  tagEs?: string;
  isAvailable?: boolean;
  isDrop?: boolean;
  dropDate?: number; // epoch ms
  dropBadgeTextEn?: string;
  dropBadgeTextEs?: string;
  dropStatus?: string;
  /** Epoch ms the product was added (Convex _creationTime); drives "Newest" sorting */
  createdAt?: number;
  /** Administrator-written description; empty/blank means unset */
  descriptionEn?: string;
  descriptionEs?: string;
  fabricEn?: string;
  fabricEs?: string;
  fitEn?: string;
  fitEs?: string;
  defaultColorway?: ApparelColorwayId;
  colorways?: ApparelColorwayOption[];
  /** Tee sizes offered (ADR 0015) */
  sizes?: string[];
}

