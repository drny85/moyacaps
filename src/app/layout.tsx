import type { Metadata, Viewport } from "next";
import { getLocale } from "next-intl/server";
import { DEFAULT_OG_IMAGE, SITE_NAME, siteUrl } from "@/lib/seo/site";
import { Anton, Inter, Space_Grotesk } from "next/font/google";
import "./globals.css";

// Fonts load with display: swap. Only the poster face (hero / page headlines) is
// preloaded; body and UI text paint in the metric-matched fallback first, so the other
// two files never compete with the LCP image for bandwidth.
const inter = Inter({
  subsets: ["latin"],
  variable: "--font-sans",
  preload: false,
});

const spaceGrotesk = Space_Grotesk({
  subsets: ["latin"],
  variable: "--font-display",
  weight: ["400", "500", "600", "700"],
  preload: false,
});

// Condensed poster face — homepage headlines only
const anton = Anton({
  subsets: ["latin"],
  variable: "--font-poster",
  weight: "400",
  preload: true,
});

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl()),
  applicationName: SITE_NAME,
  title: "Good Luck | 0880 Signature Caps & Heavyweight Tees",
  description: "Official Good Luck store: 0880 caps with heavyweight 3D puff embroidery and boxy 280 GSM graphic tees.",
  robots: {
    index: true,
    follow: true,
    googleBot: { index: true, follow: true, "max-image-preview": "large", "max-snippet": -1, "max-video-preview": -1 },
  },
  // Pages that set no Open Graph image still share with the brand card
  openGraph: { type: "website", siteName: SITE_NAME, images: [{ url: DEFAULT_OG_IMAGE, width: 1200, height: 630 }] },
  twitter: { card: "summary_large_image" },
  // Google Search Console HTML-tag verification (Settings → Ownership verification → HTML tag → content value)
  verification: process.env.GOOGLE_SITE_VERIFICATION ? { google: process.env.GOOGLE_SITE_VERIFICATION } : undefined,
  // Site icons come from src/app/icon.png and apple-icon.png (generated by `bun run build-catalog-shots`).
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#ffffff" },
    { media: "(prefers-color-scheme: dark)", color: "#09090b" },
  ],
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Per-locale lang so Google and screen readers read /es pages as Spanish
  const locale = await getLocale();

  return (
    <html lang={locale} className="light scroll-smooth" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  var stored = localStorage.getItem('moyacaps-storage');
                  if (stored) {
                    var parsed = JSON.parse(stored);
                    if (parsed.state && parsed.state.theme === 'dark') {
                      document.documentElement.classList.remove('light');
                      document.documentElement.classList.add('dark');
                      document.documentElement.style.colorScheme = 'dark';
                      return;
                    }
                  }
                  document.documentElement.classList.remove('dark');
                  document.documentElement.classList.add('light');
                  document.documentElement.style.colorScheme = 'light';
                } catch (e) {}
              })();
            `,
          }}
        />
      </head>
      <body className={`${inter.variable} ${spaceGrotesk.variable} ${anton.variable} font-sans bg-background text-foreground antialiased min-h-screen selection:bg-moya-red selection:text-white transition-colors duration-300`}>
        {children}
      </body>
    </html>
  );
}
